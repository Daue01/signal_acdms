#!/usr/bin/env node

import {readFile, writeFile} from 'node:fs/promises';

const usage=`Usage:
  node scripts/import-geography.mjs --input geography.csv --output supabase/010_seed_geography.sql

Input columns:
  state,lga,ward

The input must be an authoritative State/LGA/Ward extract. The script validates,
deduplicates exact rows, sorts deterministically, and emits rerunnable SQL for
public.states, public.lgas, public.wards, and enumeration_areas. It does not
invent geography or load an unverified dataset.
`;

function args(argv){
 const result={};
 for(let i=0;i<argv.length;i++){
  const arg=argv[i];
  if(arg==='--help'||arg==='-h'){console.log(usage);process.exit(0)}
  if(arg.startsWith('--'))result[arg.slice(2)]=argv[++i];
 }
 return result;
}

function parseCsv(text){
 const rows=[];let row=[];let cell='';let quoted=false;
 for(let i=0;i<text.length;i++){
  const char=text[i];
  if(quoted){
   if(char==='"'&&text[i+1]==='"'){cell+='"';i++}
   else if(char==='"')quoted=false;
   else cell+=char;
  }else if(char==='"')quoted=true;
  else if(char===','){row.push(cell);cell=''}
  else if(char==='\n'){row.push(cell);rows.push(row);row=[];cell=''}
  else if(char!=='\r')cell+=char;
 }
 if(quoted)throw new Error('CSV contains an unclosed quoted field');
 if(cell.length||row.length){row.push(cell);rows.push(row)}
 return rows.filter(item=>item.some(value=>value.trim().length));
}

const sql=value=>`'${value.replaceAll("'","''")}'`;
const clean=value=>value.replace(/^\uFEFF/,'').trim().replace(/\s+/g,' ');
const key=parts=>parts.map(item=>item.toLocaleLowerCase('en-GB')).join('\u0000');

const options=args(process.argv.slice(2));
if(!options.input){console.error(usage);process.exit(2)}
const input=await readFile(options.input,'utf8');
const rows=parseCsv(input);
if(!rows.length)throw new Error('Input CSV is empty');
const headers=rows.shift().map(clean).map(value=>value.toLowerCase());
for(const required of ['state','lga','ward'])if(!headers.includes(required))throw new Error(`Missing required CSV column: ${required}`);
const indexes=Object.fromEntries(['state','lga','ward'].map(name=>[name,headers.indexOf(name)]));
const records=[];const seen=new Set();
for(const [line,row] of rows.entries()){
 const record={state:clean(row[indexes.state]??''),lga:clean(row[indexes.lga]??''),ward:clean(row[indexes.ward]??'')};
 if(Object.values(record).some(value=>!value))throw new Error(`Blank geography value near CSV line ${line+2}`);
 if(Object.values(record).some(value=>value.includes('\0')))throw new Error(`Invalid NUL character near CSV line ${line+2}`);
 const identity=key(Object.values(record));
 if(!seen.has(identity)){seen.add(identity);records.push(record)}
}
if(!records.length)throw new Error('Input CSV has no geography records');
records.sort((a,b)=>key(Object.values(a)).localeCompare(key(Object.values(b))));
const states=[...new Map(records.map(item=>[key([item.state]),item.state])).values()].sort((a,b)=>a.localeCompare(b));
const lgas=[...new Map(records.map(item=>[key([item.state,item.lga]),item])).values()].sort((a,b)=>key([a.state,a.lga]).localeCompare(key([b.state,b.lga])));
const wards=records;
const values=list=>list.map(item=>`  (${item.map(sql).join(', ')})`).join(',\n');
const sqlOutput=`-- Generated by scripts/import-geography.mjs. Do not edit by hand.
-- Source rows: ${records.length}; states: ${states.length}; LGAs: ${lgas.length}; wards: ${wards.length}.
begin;

insert into public.states(name)
values
${values(states.map(name=>[name]))}
on conflict (name) do nothing;

insert into public.lgas(state_id, name)
select s.state_id, v.lga_name
from (values
${values(lgas.map(item=>[item.state,item.lga]))}
) as v(state_name, lga_name)
join public.states s on s.name = v.state_name
on conflict (state_id, name) do nothing;

insert into public.wards(lga_id, name)
select l.lga_id, v.ward_name
from (values
${values(wards.map(item=>[item.state,item.lga,item.ward]))}
) as v(state_name, lga_name, ward_name)
join public.states s on s.name = v.state_name
join public.lgas l on l.state_id = s.state_id and l.name = v.lga_name
on conflict (lga_id, name) do nothing;

update public.enumeration_areas ea
set ward_id = w.ward_id
from public.states s
join public.lgas l on l.state_id = s.state_id
join public.wards w on w.lga_id = l.lga_id
where lower(btrim(ea.state)) = lower(s.name)
  and lower(btrim(ea.lga)) = lower(l.name)
  and lower(btrim(ea.ward)) = lower(w.name)
  and (ea.ward_id is null or ea.ward_id <> w.ward_id);

commit;

-- Verification queries:
-- select count(*) as states from public.states;
-- select count(*) as lgas from public.lgas;
-- select count(*) as wards from public.wards;
-- select ea_code, state, lga, ward from public.enumeration_areas where ward_id is null;
`;
if(options.output)await writeFile(options.output,sqlOutput,'utf8');
else process.stdout.write(sqlOutput);
console.error(`Prepared ${records.length} rows (${states.length} states, ${lgas.length} LGAs, ${wards.length} wards).`);
